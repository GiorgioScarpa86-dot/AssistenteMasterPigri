export const getMonstersByBiome = (biome: BiomeId): Monster[] => {
  return MONSTERS.filter(m => m.biomes.includes(biome));
};

export const getMonstersByCRRange = (monsters: Monster[], minCR: number, maxCR: number) => {
  return monsters.filter(m => m.crNum >= minCR && m.crNum <= maxCR);
};
